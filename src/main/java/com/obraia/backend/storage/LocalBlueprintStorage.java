package com.obraia.backend.storage;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;

import com.obraia.backend.entity.blueprint.StorageProvider;

/** Keeps the files in a folder of the computer. Handy in development; the folder is not in Git. */
public class LocalBlueprintStorage implements BlueprintStorage {

    private final Path root;

    public LocalBlueprintStorage(Path root) {
        this.root = root.toAbsolutePath().normalize();
    }

    @Override
    public StorageProvider provider() {
        return StorageProvider.LOCAL;
    }

    @Override
    public void save(String key, byte[] content) {
        Path file = resolve(key);
        try {
            Files.createDirectories(file.getParent());
            Files.write(file, content);
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not save the file " + key, ex);
        }
    }

    @Override
    public byte[] load(String key) {
        try {
            return Files.readAllBytes(resolve(key));
        } catch (NoSuchFileException ex) {
            throw new StoredFileNotFoundException(key);
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not read the file " + key, ex);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not delete the file " + key, ex);
        }
    }

    /** The keys are generated by the backend, but a key can never point outside the folder. */
    private Path resolve(String key) {
        Path file = root.resolve(key).normalize();
        if (!file.startsWith(root)) {
            throw new IllegalArgumentException("Invalid storage key: " + key);
        }
        return file;
    }
}
